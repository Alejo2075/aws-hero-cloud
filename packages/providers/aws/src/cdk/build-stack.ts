import {
  Duration,
  PermissionsBoundary,
  RemovalPolicy,
  Stack,
  Tags,
  Validations,
} from 'aws-cdk-lib';
import type { StackProps } from 'aws-cdk-lib';
import * as codebuild from 'aws-cdk-lib/aws-codebuild';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as s3 from 'aws-cdk-lib/aws-s3';
import type { Construct } from 'constructs';
import { BUILD_IMAGE, BUILD_TIMEOUT_MINUTES } from '../build/plan.js';
import { BOUNDARY_POLICY_NAME } from './names.js';

export interface BuildStackProps extends StackProps {
  readonly deploymentId: string;
}

/** The key prefixes inside the build bucket. The role can touch nothing else. */
export const SOURCE_PREFIX = 'source/';
export const ARTIFACT_PREFIX = 'artifacts/';

/**
 * Where a deployment is built, inside the person's own account. The build role can read the
 * uploaded source, write the artifacts, and write its own logs. It has no other permission and
 * the person's credentials never enter the build.
 */
export class BuildStack extends Stack {
  constructor(scope: Construct, id: string, props: BuildStackProps) {
    super(scope, id, {
      ...props,
      permissionsBoundary: PermissionsBoundary.fromName(BOUNDARY_POLICY_NAME),
    });
    Tags.of(this).add('hero:deployment-id', props.deploymentId);

    const accessLogs = new s3.Bucket(this, 'AccessLogs', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      objectOwnership: s3.ObjectOwnership.OBJECT_WRITER,
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: false,
      lifecycleRules: [{ expiration: Duration.days(30) }],
    });
    const bucket = new s3.Bucket(this, 'Artifacts', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      versioned: true,
      objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
      removalPolicy: RemovalPolicy.DESTROY,
      serverAccessLogsBucket: accessLogs,
      serverAccessLogsPrefix: 'artifacts/',
      lifecycleRules: [
        { prefix: SOURCE_PREFIX, expiration: Duration.days(7) },
        { prefix: ARTIFACT_PREFIX, noncurrentVersionExpiration: Duration.days(30) },
      ],
    });
    const logGroup = new logs.LogGroup(this, 'BuildLogs', {
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: RemovalPolicy.DESTROY,
    });

    const role = new iam.Role(this, 'BuildRole', {
      assumedBy: new iam.ServicePrincipal('codebuild.amazonaws.com'),
      description: 'Reads the uploaded source, writes build artifacts and logs. Nothing else.',
    });
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ['s3:GetObject', 's3:GetObjectVersion'],
        resources: [bucket.arnForObjects(`${SOURCE_PREFIX}*`)],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ['s3:PutObject'],
        resources: [bucket.arnForObjects(`${ARTIFACT_PREFIX}*`)],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ['logs:CreateLogStream', 'logs:PutLogEvents'],
        resources: [logGroup.logGroupArn, `${logGroup.logGroupArn}:*`],
      }),
    );

    // The low-level resource is used on purpose: the high-level Project quietly grants its role
    // wide bucket permissions, and this role must hold exactly the three statements above.
    const projectName = `${props.deploymentId}-build`;
    const project = new codebuild.CfnProject(this, 'Project', {
      name: projectName,
      description:
        'Builds the application in this account. Its commands are part of the approved plan.',
      serviceRole: role.roleArn,
      timeoutInMinutes: BUILD_TIMEOUT_MINUTES,
      source: { type: 'S3', location: `${bucket.bucketName}/${SOURCE_PREFIX}placeholder.zip` },
      artifacts: {
        type: 'S3',
        location: bucket.bucketName,
        path: ARTIFACT_PREFIX,
        namespaceType: 'NONE',
        packaging: 'ZIP',
        name: 'placeholder.zip',
        encryptionDisabled: false,
      },
      environment: {
        type: 'ARM_CONTAINER',
        image: BUILD_IMAGE,
        computeType: 'BUILD_GENERAL1_SMALL',
        privilegedMode: false,
      },
      // The real buildspec is generated by Hero and sent with each build; the project never reads
      // one from the source.
      logsConfig: { cloudWatchLogs: { status: 'ENABLED', groupName: logGroup.logGroupName } },
    });
    project.addPropertyOverride(
      'Source.BuildSpec',
      JSON.stringify({ version: '0.2', phases: { build: { commands: ['true'] } } }),
    );

    const wildcard = (rule: string, finding: string, reason: string, target: Construct): void => {
      Validations.of(target).acknowledge({ id: `AwsSolutions::${rule}[${finding}]`, reason });
    };
    wildcard(
      'AwsSolutions-IAM5',
      `Resource::<${this.getLogicalId(bucket.node.defaultChild as never)}.Arn>/${SOURCE_PREFIX}*`,
      'The build role may read only the source objects uploaded for this deployment.',
      role,
    );
    wildcard(
      'AwsSolutions-IAM5',
      `Resource::<${this.getLogicalId(bucket.node.defaultChild as never)}.Arn>/${ARTIFACT_PREFIX}*`,
      'The build role may write only the artifact objects of this deployment.',
      role,
    );
    wildcard(
      'AwsSolutions-IAM5',
      `Resource::<${this.getLogicalId(logGroup.node.defaultChild as never)}.Arn>:*`,
      "The build role may write the log streams of this deployment's build log group.",
      role,
    );
    Validations.of(project).acknowledge({
      id: 'AwsSolutions::AwsSolutions-CB4',
      reason:
        'Build artifacts are encrypted with the AWS-managed S3 key; a customer-managed key would add cost and a shared key to manage for a short-lived build.',
    });

    this.exportValue(bucket.bucketName, { name: `${props.deploymentId}-build-bucket` });
    this.exportValue(projectName, { name: `${props.deploymentId}-build-project` });
  }
}
